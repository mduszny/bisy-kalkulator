def pobierz_dane_hydrostatyczne():
    try:
        t_input = float(input("Podaj zanurzenie średnie statku T [m]: "))
        t_klucz = f"{t_input:.2f}"

        if t_klucz in baza_hydrostatyczna:
            dane = baza_hydrostatyczna[t_klucz]
            print(f"\nDane hydrostatyczne dla zanurzenia T = {t_klucz} m:")
            print("-" * 45)
            print(f"Objętość podwodzia (V):               {dane['V']} m3")
            print(f"Wyporność statku (D):                 {dane['D']} t")
            print(f"Przyrost wyporności (TPC):            {dane['TPC']} t/cm")
            print(f"Rzędna metacentrum (ZM):              {dane['ZM']} m")
            print(f"Jednostkowy moment przegłębiający (Mj): {dane['Mj']} tm/m")
            print(f"Odcięta środka wyporu (XF):           {dane['XF']} m")
            print(f"Odcięta środka wodnicy (XS):          {dane['XS']} m")
            print(f"Współczynnik pełnotliwości wodnicy (alpha): {dane['alpha']}")
            print(f"Współczynnik pełnotliwości kadłuba (delta): {dane['delta']}")
            print("-" * 45)
        else:
            print(f"\nBrak danych w bazie dla podanego zanurzenia T = {t_klucz} m.")

    except ValueError:
        print("\nBłąd: Wprowadzono nieprawidłową wartość. Proszę podać liczbę.")


